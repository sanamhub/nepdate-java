package io.github.sanamhub.nepdate.java.codegen;

/** Renders the core calendar table from the hub's month lengths. */
final class CalendarTableGenerator {
  private CalendarTableGenerator() {}

  static String render(CalendarData data) {
    int totalDays = data.totalDays();
    int maxSerial = totalDays - 1;
    int epochUnixDays = CalendarData.daysFromCivil(1844, 4, 11);
    int epochWeekday = CalendarData.weekdayOf(epochUnixDays);
    CalendarData.require(epochWeekday == 4, "1844-04-11 is not a Thursday");

    StringBuilder out = new StringBuilder(16_000);
    out.append(
            "// Generated by :codegen from shared/data/calendar/bs-calendar.json. DO NOT EDIT.\n")
        .append("//\n")
        .append(
            "// The month lengths are checked against the data by :codegen --check and by the\n")
        .append(
            "// exhaustive tests. Change the data in the hub, then run ./gradlew :codegen:run.\n")
        .append("\n")
        .append("package io.github.sanamhub.nepdate.java;\n")
        .append("\n")
        .append("/**\n")
        .append(
            " * The BS month lengths and the constants derived from them (ALGORITHM sections 1 and\n")
        .append(" * 2). Package-private: the numbers are data, and the API exposes only dates.\n")
        .append(" */\n")
        .append("final class CalendarTable {\n")
        .append("  /** First and last BS year with data. */\n")
        .append("  static final int MIN_YEAR = ")
        .append(CalendarData.MIN_YEAR)
        .append(";\n")
        .append("  static final int MAX_YEAR = ")
        .append(CalendarData.MAX_YEAR)
        .append(";\n")
        .append("\n")
        .append("  /** Number of BS years, and of BS months from 1901-01 to 2199-12. */\n")
        .append("  static final int YEARS = ")
        .append(CalendarData.YEARS)
        .append(";\n")
        .append("  static final int MONTHS = ")
        .append(CalendarData.YEARS * 12)
        .append(";\n")
        .append("\n")
        .append("  /** Serial of 1901-01-01, and of the last supported day, 2199-12-30. */\n")
        .append("  static final int MIN_SERIAL = 0;\n")
        .append("  static final int MAX_SERIAL = ")
        .append(maxSerial)
        .append(";\n")
        .append("  static final int TOTAL_DAYS = ")
        .append(totalDays)
        .append(";\n")
        .append("\n")
        .append(
            "  /** Days from AD 1970-01-01 to 1844-04-11, and that day's weekday (0 = Sunday). */\n")
        .append("  static final int EPOCH_UNIX_DAYS = ")
        .append(epochUnixDays)
        .append(";\n")
        .append("  static final int EPOCH_WEEKDAY = ")
        .append(epochWeekday)
        .append(";\n")
        .append("\n")
        .append("  /** One character per month from 1901-01 to 2199-12: '0' + (length - 29). */\n")
        .append("  static final String MONTH_LENGTHS =\n");

    for (int year = CalendarData.MIN_YEAR; year <= CalendarData.MAX_YEAR; year++) {
      StringBuilder row = new StringBuilder(12);
      for (int month = 1; month <= 12; month++) {
        row.append((char) ('0' + data.monthLength(year, month) - 29));
      }
      out.append("      ");
      if (year > CalendarData.MIN_YEAR) {
        out.append("+ ");
      }
      out.append('"').append(row).append('"');
      if (year < CalendarData.MAX_YEAR) {
        out.append(" // ").append(year).append('\n');
      } else {
        out.append("; // ").append(year).append('\n');
      }
    }

    out.append("\n")
        .append("  /** Serial of the first day of each month, plus the day after 2199-12 (")
        .append(totalDays)
        .append("). */\n")
        .append("  static final int[] MONTH_START = new int[MONTHS + 1];\n")
        .append("\n")
        .append("  static {\n")
        .append("    int serial = 0;\n")
        .append("    for (int month = 0; month < MONTHS; month++) {\n")
        .append(
            "      MONTH_START[month + 1] = serial += 29 + (MONTH_LENGTHS.charAt(month) - '0');\n")
        .append("    }\n")
        .append("  }\n")
        .append("\n")
        .append("  private CalendarTable() {}\n")
        .append("}\n");
    return out.toString();
  }
}
